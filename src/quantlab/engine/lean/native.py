"""Native LEAN launcher (ENG-003) and C# algorithms (ENG-008) — LEAN on the local .NET 10 runtime, no Docker.

Install layout (``engine.lean.native_path``, created by ``quantlab engine native-install``)::

    bin/              LEAN launcher + dependencies from QuantConnect's NuGet packages (LEAN_VERSION) and
                      the QuantLab gateway brokerage (OMS-007), built from ``lean/QuantLabLauncher``
    Data/             LEAN's databases (market hours, symbol properties, interest rates) and its bundled
                      sample SPY data, from the LEAN repository at the matching tag (LEAN_DATA_TAG)
    lean-native.json  what was installed (versions, data commit, sha256 of the databases)

Runs mirror the Docker adapter: one immutable work directory per run, results parsed the same way. With a
QuantLab dataset the run gets its own data folder containing LEAN's databases plus the dataset export only —
never the sample prices — just as the Docker launcher removes them in the container. Without a dataset LEAN's
bundled sample data is used (provenance ``sample``).

C# strategies are compiled per run against the same LEAN version (compile-time references only), so the
assembly matches the engine. Python algorithms on the native launcher need pythonnet set up for Python 3.11
(KI-0078) and are refused here; use the Docker launcher for them.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import threading
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from quantlab.core.logging import get_logger
from quantlab.engine.base import (
    AlgorithmLanguage,
    BacktestSpec,
    EngineError,
    EngineInfo,
    EngineResult,
    RunHandle,
    RunOutcome,
    RunState,
)
from quantlab.engine.lean.config import LeanPaths, build_backtest_config, write_config
from quantlab.engine.lean.docker import run_layout
from quantlab.engine.lean.results import parse_results_dir

log = get_logger(__name__)

LEAN_VERSION = "2.5.18229"  # NuGet packages (lean/QuantLabLauncher, lean/QuantLabBrokerage)
LEAN_DATA_TAG = "18229"  # LEAN repository tag of the same release
LEAN_REPOSITORY = "https://github.com/QuantConnect/Lean.git"
DATABASES = ("market-hours", "symbol-properties", "alternative/interest-rate")  # needed by every run
SAMPLE_DATA = (  # LEAN's bundled sample data used by its template algorithms (provenance "sample")
    "equity/usa/minute/spy",
    "equity/usa/daily/spy.zip",
    "equity/usa/map_files/spy.csv",
    "equity/usa/factor_files/spy.csv",
)
MANIFEST = "lean-native.json"
LAUNCHER = "QuantConnect.Lean.Launcher.dll"

ALGORITHM_PROJECT = """<Project Sdk="Microsoft.NET.Sdk">
  <!-- generated by QuantLab for one run: compiles the strategy against LEAN {version} -->
  <PropertyGroup>
    <TargetFramework>net10.0</TargetFramework>
    <OutputType>Library</OutputType>
    <AssemblyName>QuantLabAlgorithm</AssemblyName>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <Nullable>disable</Nullable>
    <NuGetAudit>false</NuGetAudit>
  </PropertyGroup>
  <ItemGroup><Compile Include="{sources}/**/*.cs" /></ItemGroup>
  <ItemGroup>
    <PackageReference Include="QuantConnect.Algorithm" Version="{version}"
                      PrivateAssets="all" ExcludeAssets="runtime" />
  </ItemGroup>
</Project>
"""


def _run(
    argv: list[str], *, cwd: Path | None = None, timeout: float = 1800
) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(argv, cwd=cwd, capture_output=True, text=True, timeout=timeout, check=False)
    except FileNotFoundError as exc:
        raise EngineError(f"{argv[0]!r} not found: install the .NET 10 SDK and git") from exc
    except subprocess.TimeoutExpired as exc:
        raise EngineError(f"{' '.join(argv[:3])} timed out after {timeout}s") from exc


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def install(target: Path, repo_root: Path, *, dotnet: str = "dotnet", git: str = "git") -> dict[str, Any]:
    """Build the launcher and fetch LEAN's databases + sample data (needs network once). Never overwrites."""
    if (target / MANIFEST).exists():
        raise EngineError(f"a native LEAN install already exists at {target} (remove it to reinstall)")
    project = repo_root / "lean" / "QuantLabLauncher"
    if not (project / "QuantLabLauncher.csproj").is_file():
        raise EngineError(f"launcher project not found at {project}")
    build = _run([dotnet, "build", str(project), "-c", "Release", "-o", str(target / "bin")])
    if build.returncode != 0:
        raise EngineError("building the LEAN launcher failed:\n" + (build.stdout + build.stderr)[-2000:])
    checkout = target / ".lean-src"
    shutil.rmtree(checkout, ignore_errors=True)
    steps = [
        [git, "clone", "--quiet", "--depth", "1", "--filter=blob:none", "--sparse", "--branch", LEAN_DATA_TAG,
         LEAN_REPOSITORY, str(checkout)],
        [git, "-C", str(checkout), "sparse-checkout", "set", "--no-cone",
         *[f"/Data/{p}" for p in (*DATABASES, *SAMPLE_DATA)]],
    ]  # fmt: skip
    for argv in steps:
        result = _run(argv)
        if result.returncode != 0:
            raise EngineError(f"fetching LEAN data failed: {result.stderr.strip()[:500]}")
    commit = _run([git, "-C", str(checkout), "rev-parse", "HEAD"]).stdout.strip()
    shutil.copytree(checkout / "Data", target / "Data")
    shutil.rmtree(checkout, ignore_errors=True)
    manifest = {
        "lean_version": LEAN_VERSION,
        "lean_data_tag": LEAN_DATA_TAG,
        "lean_data_commit": commit,
        "installed_at": datetime.now(UTC).isoformat(),
        "databases_sha256": {
            str(p.relative_to(target / "Data")): _sha256(p)
            for db in DATABASES
            for p in sorted((target / "Data" / db).rglob("*"))
            if p.is_file()
        },
    }
    (target / MANIFEST).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


LIVE_ENVIRONMENT = "live-quantlab"
# Data-queue handlers a QuantLab live config may use: they supply prices only, never a brokerage connection.
ALLOWED_DATA_QUEUES = frozenset(
    {
        "QuantLabDataQueue",  # QuantLab's quotes through the gateway (the risk gate's prices)
        "QuantConnect.Lean.Engine.DataFeeds.Queues.FakeDataQueue",  # LEAN's synthetic ticks (tests)
    }
)


def build_live_config(
    *,
    algorithm_location: str,
    type_name: str,
    algorithm_id: str,
    gateway_file: str,
    data_folder: str,
    results: str,
    storage: str,
    data_queue_handler: str,
    force_exchange_open: bool = False,
) -> dict[str, Any]:
    """LEAN live-mode configuration routing every order through the QuantLab gateway (OMS-007).

    The brokerage is always ``QuantLabBrokerage`` (orders → QuantLab OMS → risk gate → paper broker); LEAN's
    own brokerages are never configured. ``data_queue_handler`` supplies live prices to the algorithm (e.g.
    LEAN's ``FakeDataQueue`` for synthetic tests); the risk gate always uses QuantLab's own quotes.
    """
    if data_queue_handler not in ALLOWED_DATA_QUEUES:
        raise EngineError(
            f"data-queue handler {data_queue_handler!r} is not allowed "
            f"(allowed: {sorted(ALLOWED_DATA_QUEUES)}); "
            "brokerage data handlers could open a broker connection"
        )
    return {
        "environment": LIVE_ENVIRONMENT,
        "algorithm-type-name": type_name,
        "algorithm-language": "CSharp",
        "algorithm-location": algorithm_location,
        "algorithm-id": algorithm_id,
        "data-folder": data_folder,
        "results-destination-folder": results,
        "object-store-root": storage,
        "close-automatically": True,
        "debugging": False,
        "debugging-method": "LocalCmdline",
        "composer-dll-directory": ".",
        "job-user-id": "0",
        "api-access-token": "",
        "job-organization-id": "",
        "log-handler": "QuantConnect.Logging.CompositeLogHandler",
        "messaging-handler": "QuantConnect.Messaging.Messaging",
        "job-queue-handler": "QuantConnect.Queues.JobQueue",
        "api-handler": "QuantConnect.Api.Api",
        "map-file-provider": "QuantConnect.Data.Auxiliary.LocalDiskMapFileProvider",
        "factor-file-provider": "QuantConnect.Data.Auxiliary.LocalDiskFactorFileProvider",
        "data-provider": "QuantConnect.Lean.Engine.DataFeeds.DefaultDataProvider",
        "parameters": {},
        "quantlab-gateway-file": gateway_file,
        # Tests with synthetic quotes only: LEAN delivers data even while the exchange is closed.
        "force-exchange-always-open": force_exchange_open,
        "environments": {
            LIVE_ENVIRONMENT: {
                "live-mode": True,
                "live-mode-brokerage": "QuantLabBrokerage",
                "setup-handler": "QuantConnect.Lean.Engine.Setup.BrokerageSetupHandler",
                "result-handler": "QuantConnect.Lean.Engine.Results.LiveTradingResultHandler",
                "data-feed-handler": "QuantConnect.Lean.Engine.DataFeeds.LiveTradingDataFeed",
                "data-queue-handler": [data_queue_handler],
                "real-time-handler": "QuantConnect.Lean.Engine.RealTime.LiveTradingRealTimeHandler",
                "transaction-handler": (
                    "QuantConnect.Lean.Engine.TransactionHandlers.BrokerageTransactionHandler"
                ),
            }
        },
    }


def compile_csharp(source_dir: Path, out_dir: Path, *, dotnet: str = "dotnet") -> Path:
    """Compile a C# strategy directory against LEAN_VERSION; returns the assembly path."""
    if not any(source_dir.rglob("*.cs")):
        raise EngineError(f"no .cs files in {source_dir}")
    project_dir = out_dir / "project"
    project_dir.mkdir(parents=True, exist_ok=True)
    csproj = project_dir / "QuantLabAlgorithm.csproj"
    csproj.write_text(
        ALGORITHM_PROJECT.format(version=LEAN_VERSION, sources=source_dir.resolve().as_posix()),
        encoding="utf-8",
    )
    result = _run([dotnet, "build", str(csproj), "-c", "Release", "-o", str(out_dir / "bin")], timeout=900)
    (out_dir / "build.log").write_text(result.stdout + result.stderr, encoding="utf-8")
    if result.returncode != 0:
        errors = [line for line in result.stdout.splitlines() if ": error " in line]
        raise EngineError("C# strategy does not compile:\n" + "\n".join(dict.fromkeys(errors))[:3000])
    return out_dir / "bin" / "QuantLabAlgorithm.dll"


def _default_models(models: Any) -> bool:
    from quantlab.core.config import ExecutionModelSettings

    defaults = ExecutionModelSettings().model_dump()
    return all(defaults.get(k) == v for k, v in dict(models).items())


class LeanNativeAdapter:
    """EngineAdapter running LEAN with the local .NET runtime."""

    name = "lean"
    launcher = "native"

    def __init__(
        self,
        install_dir: Path,
        *,
        dotnet: str = "dotnet",
        default_timeout_s: float | None = None,
    ) -> None:
        self.install_dir = install_dir
        self.dotnet = dotnet
        self.default_timeout_s = default_timeout_s
        self._procs: dict[str, subprocess.Popen[bytes]] = {}
        self._started: dict[str, float] = {}
        self._cancelled: set[str] = set()
        self._lock = threading.Lock()

    def _manifest(self) -> dict[str, Any]:
        path = self.install_dir / MANIFEST
        if not path.is_file() or not (self.install_dir / "bin" / LAUNCHER).is_file():
            raise EngineError(
                f"no native LEAN install at {self.install_dir}: run `quantlab engine native-install` first"
            )
        data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
        return data

    # ---- EngineAdapter -----------------------------------------------------------------------
    def probe(self) -> EngineInfo:
        manifest = self._manifest()
        version = _run([self.dotnet, "--version"], timeout=60)
        if version.returncode != 0:
            raise EngineError(".NET SDK not available: " + version.stderr.strip()[:300])
        return EngineInfo(
            name=self.name,
            launcher=self.launcher,
            image=f"lean-native {manifest['lean_version']} (data {manifest['lean_data_commit'][:12]})",
            image_id=manifest["lean_data_commit"],
            created=manifest.get("installed_at"),
            engine_runtime_version=f"dotnet {version.stdout.strip()}",
        )

    def start_backtest(self, spec: BacktestSpec) -> RunHandle:
        self._manifest()
        algo = spec.algorithm
        if not algo.entry_path.is_file():
            raise EngineError(f"algorithm entry file not found: {algo.entry_path}")
        if algo.language is AlgorithmLanguage.PYTHON:
            raise EngineError(
                "the native launcher runs C# algorithms; Python algorithms need pythonnet for Python 3.11 "
                "(KI-0078) — use engine.lean.launcher = 'docker' for them"
            )
        if spec.models is not None and not _default_models(spec.models):
            raise EngineError(
                "custom execution models (ENG-009) are applied through the Python helper library only; "
                "C# strategies on the native launcher use LEAN's brokerage defaults"
            )
        if spec.data_dir is not None and not spec.data_dir.is_dir():
            raise EngineError(f"data directory not found: {spec.data_dir}")
        handle = run_layout(spec)
        if handle.work_dir.exists() and any(handle.work_dir.iterdir()):
            raise EngineError(f"run directory already exists and is not empty: {handle.work_dir}")
        handle.results_dir.mkdir(parents=True, exist_ok=True)
        (handle.work_dir / "storage").mkdir(parents=True, exist_ok=True)
        assembly = compile_csharp(algo.directory, handle.work_dir / "algorithm", dotnet=self.dotnet)
        data_folder = self._data_folder(spec, handle)
        paths = LeanPaths(
            algorithm_location=str(assembly),
            data_folder=str(data_folder) + "/",
            results=str(handle.results_dir),
            storage=str(handle.work_dir / "storage"),
        )
        write_config(build_backtest_config(spec, paths), handle.config_path)
        argv = [self.dotnet, LAUNCHER, "--config", str(handle.config_path)]
        (handle.work_dir / "native-command.json").write_text(
            json.dumps(argv, indent=2) + "\n", encoding="utf-8"
        )
        log_file = handle.log_path.open("wb")
        try:
            proc = subprocess.Popen(
                argv, cwd=self.install_dir / "bin", stdout=log_file, stderr=subprocess.STDOUT
            )
        except FileNotFoundError as exc:
            raise EngineError(f"dotnet not found: {self.dotnet!r}") from exc
        finally:
            log_file.close()  # the child holds its own handle
        with self._lock:
            self._procs[spec.run_id] = proc
            self._started[spec.run_id] = time.monotonic()
        log.info("engine.started", run_id=spec.run_id, launcher="native")
        return handle

    def _data_folder(self, spec: BacktestSpec, handle: RunHandle) -> Path:
        install_data = self.install_dir / "Data"
        if spec.data_dir is None:
            return install_data  # LEAN's sample data (provenance "sample")
        # A dataset run sees LEAN's databases and the dataset only — never the bundled sample prices.
        run_data = handle.work_dir / "data"
        for db in DATABASES:
            shutil.copytree(install_data / db, run_data / db)
        shutil.copytree(
            spec.data_dir,
            run_data,
            dirs_exist_ok=True,
            ignore=shutil.ignore_patterns("quantlab-lean-export.json"),
        )
        return run_data

    def wait(self, handle: RunHandle, timeout_s: float | None = None) -> RunOutcome:
        with self._lock:
            proc = self._procs.get(handle.run_id)
            started = self._started.get(handle.run_id, time.monotonic())
        if proc is None:
            raise EngineError(f"unknown run {handle.run_id} (not started by this adapter)")
        timeout_s = self.default_timeout_s if timeout_s is None else timeout_s
        try:
            code = proc.wait(timeout=timeout_s)
        except subprocess.TimeoutExpired:
            proc.terminate()
            try:
                proc.wait(timeout=30)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait()
            outcome = RunOutcome(RunState.TIMED_OUT, proc.returncode, time.monotonic() - started,
                                 f"exceeded {timeout_s}s; engine stopped")  # fmt: skip
        else:
            duration = time.monotonic() - started
            if handle.run_id in self._cancelled:
                outcome = RunOutcome(RunState.CANCELLED, code, duration, "cancelled by user")
            elif code == 0:
                outcome = RunOutcome(RunState.SUCCEEDED, code, duration)
            else:
                outcome = RunOutcome(RunState.FAILED, code, duration, f"engine exited with code {code}")
        with self._lock:
            self._procs.pop(handle.run_id, None)
        log.info("engine.finished", run_id=handle.run_id, state=outcome.state, exit_code=outcome.exit_code)
        return outcome

    def cancel(self, handle: RunHandle) -> None:
        with self._lock:
            self._cancelled.add(handle.run_id)
            proc = self._procs.get(handle.run_id)
        if proc is not None and proc.poll() is None:
            proc.terminate()

    def collect(self, handle: RunHandle) -> EngineResult:
        return parse_results_dir(handle.results_dir, handle.run_id)
